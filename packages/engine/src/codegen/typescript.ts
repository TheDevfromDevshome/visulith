import { error, hasErrors, type Diagnostic, type SourceRef } from "../diagnostics.js";
import {
  IR_VERSION,
  type IrExpression,
  type IrModule,
  type IrStatement,
  type SourceMapping,
} from "../ir/types.js";

export const TYPESCRIPT_BACKEND_VERSION = "0.1";

export interface CodegenResult {
  ok: boolean;
  source?: string;
  sourceMap: SourceMapping[];
  diagnostics: Diagnostic[];
}

const CALL_TARGETS: Readonly<Record<string, string>> = {
  "core.console.log": "console.log",
};

const RESERVED = new Set(["break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do", "else", "enum", "export", "extends", "false", "finally", "for", "function", "if", "import", "in", "instanceof", "let", "new", "null", "return", "super", "switch", "this", "throw", "true", "try", "typeof", "var", "void", "while", "with", "yield"]);

function isIdentifier(value: string): boolean {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(value) && !RESERVED.has(value);
}

function renderExpression(expression: IrExpression): string | undefined {
  switch (expression.kind) {
    case "string":
      return JSON.stringify(expression.value);
    case "integer":
    case "float":
      return String(expression.value);
    case "boolean":
      return expression.value ? "true" : "false";
    case "variable":
      return isIdentifier(expression.name) ? expression.name : undefined;
    case "binary": {
      const left = renderExpression(expression.left);
      const right = renderExpression(expression.right);
      return left !== undefined && right !== undefined ? `${left} ${expression.operator} ${right}` : undefined;
    }
    default:
      return undefined;
  }
}

/** Deterministic TypeScript backend for the supported IR subset. */
export function generateTypeScript(ir: IrModule): CodegenResult {
  const diagnostics: Diagnostic[] = [];
  const sourceMap: SourceMapping[] = [];
  if (ir.irVersion !== IR_VERSION) {
    diagnostics.push(
      error(
        "CODEGEN_IR_VERSION_UNSUPPORTED",
        `IR version "${ir.irVersion}" is not supported by the TypeScript backend ${TYPESCRIPT_BACKEND_VERSION}.`,
      ),
    );
    return { ok: false, sourceMap, diagnostics };
  }

  const lines: string[] = [];
  const emit = (text: string, origin?: SourceRef, column = 1): void => {
    lines.push(text);
    if (origin !== undefined) sourceMap.push({ generatedLine: lines.length, generatedColumn: column, origin });
  };
  const indent = (level: number): string => "  ".repeat(level);
  let loopCounter = 0;

  emit(`// Generated by Visulith TypeScript backend ${TYPESCRIPT_BACKEND_VERSION}. Do not edit by hand.`);
  emit(`// module: ${ir.id}`);
  emit("");

  for (const fn of ir.functions) {
    if (!isIdentifier(fn.id)) {
      diagnostics.push(error("CODEGEN_INVALID_IDENTIFIER", `Function id "${fn.id}" is not a valid TypeScript identifier.`));
      continue;
    }
    if (fn.parameters.length > 0 || fn.returnType.name !== "core.unit") {
      diagnostics.push(
        error(
          "CODEGEN_UNSUPPORTED_SIGNATURE",
          "The TypeScript MVP backend only supports zero-argument functions returning core.unit.",
          fn.origin,
        ),
      );
      continue;
    }

    emit(`function ${fn.id}(): void {`, fn.origin);
    for (const statement of fn.body) emitStatement(statement, 1);
    emit("}");
    emit("");
    emit(`${fn.id}();`, fn.origin);
  }

  function emitStatement(statement: IrStatement, level: number): void {
    const origin = statement.origin;
    const prefix = indent(level);

    if (statement.kind === "call") {
      const target = CALL_TARGETS[statement.target];
      if (target === undefined) {
        diagnostics.push(
          error(
            "CODEGEN_UNSUPPORTED_CALL",
            `Call target "${statement.target}" has no TypeScript mapping.`,
            origin,
            "Implement a backend mapping or use an external source module.",
          ),
        );
        return;
      }
      const renderedArguments = statement.arguments.map(renderExpression);
      if (renderedArguments.some((value) => value === undefined)) {
        diagnostics.push(error("CODEGEN_UNSUPPORTED_EXPRESSION", "An IR expression cannot be generated.", origin));
        return;
      }
      emit(`${prefix}${target}(${renderedArguments.join(", ")});`, origin, level * 2 + 1);
      return;
    }

    if (statement.kind === "variable") {
      if (!isIdentifier(statement.name)) {
        diagnostics.push(
          error("CODEGEN_INVALID_IDENTIFIER", `Variable name "${statement.name}" is not a valid TypeScript identifier.`, origin),
        );
        return;
      }
      const value = renderExpression(statement.value);
      if (value === undefined) {
        diagnostics.push(error("CODEGEN_UNSUPPORTED_EXPRESSION", "An IR expression cannot be generated.", origin));
        return;
      }
      emit(`${prefix}const ${statement.name}: string = ${value};`, origin, level * 2 + 1);
      return;
    }

    if (statement.kind === "conditional") {
      const condition = renderExpression(statement.condition);
      if (condition === undefined) {
        diagnostics.push(error("CODEGEN_UNSUPPORTED_EXPRESSION", "A condition cannot be generated.", origin));
        return;
      }
      emit(`${prefix}if (${condition}) {`, origin, level * 2 + 1);
      for (const nested of statement.thenBody) emitStatement(nested, level + 1);
      if (statement.elseBody.length > 0) {
        emit(`${prefix}} else {`, origin, level * 2 + 1);
        for (const nested of statement.elseBody) emitStatement(nested, level + 1);
      }
      emit(`${prefix}}`, origin, level * 2 + 1);
      return;
    }

    if (statement.kind === "loop") {
      const count = renderExpression(statement.count);
      if (count === undefined) {
        diagnostics.push(error("CODEGEN_UNSUPPORTED_LOOP_COUNT", "A loop count cannot be generated.", origin));
        return;
      }
      const variable = `__visulith_loop_${loopCounter++}`;
      emit(`${prefix}for (let ${variable} = 0; ${variable} < ${count}; ${variable}++) {`, origin, level * 2 + 1);
      for (const nested of statement.body) emitStatement(nested, level + 1);
      emit(`${prefix}}`, origin, level * 2 + 1);
      return;
    }

    if (statement.kind === "return") {
      if (statement.value !== undefined) {
        diagnostics.push(
          error("CODEGEN_UNSUPPORTED_RETURN_VALUE", "Return values are not supported for core.unit functions.", origin),
        );
        return;
      }
      emit(`${prefix}return;`, origin, level * 2 + 1);
      return;
    }

    diagnostics.push(error("CODEGEN_UNSUPPORTED_STATEMENT", "Unsupported IR statement.", origin));
  }

  if (hasErrors(diagnostics)) return { ok: false, sourceMap, diagnostics };
  return { ok: true, source: `${lines.join("\n")}\n`, sourceMap, diagnostics };
}
